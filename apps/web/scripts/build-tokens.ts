import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

// Builds web/src/styles/tokens.css from the DTCG source in web/tokens/. The JSON is the
// single source of truth: every token that names CSS properties in $extensions["relay.css"]
// is emitted under :root: the site is dark only, so there is one set of values. Run after
// editing a token: `bun run tokens`.

type Node = { [key: string]: unknown };

const TOKENS_DIR = path.resolve(import.meta.dirname, '../web/tokens');
export const OUTPUT = path.resolve(import.meta.dirname, '../web/src/styles/tokens.css');

const read = (name: string): Node => JSON.parse(readFileSync(path.join(TOKENS_DIR, name), 'utf8'));

function get(root: Node, dotted: string): Node | undefined {
  let node: unknown = root;
  for (const key of dotted.split('.')) {
    if (!node || typeof node !== 'object' || !(key in node)) return undefined;
    node = (node as Node)[key];
  }
  return node as Node | undefined;
}

function resolveValue(root: Node, value: unknown, depth = 0): string {
  if (depth > 12) throw new Error(`alias loop at ${String(value)}`);
  if (typeof value !== 'string') throw new Error(`non-string token value: ${JSON.stringify(value)}`);
  const alias = /^\{([^}]+)\}$/.exec(value);
  if (!alias) return value;
  return resolveValue(root, tokenValue(root, alias[1]), depth + 1);
}

function tokenValue(root: Node, dotted: string): unknown {
  const node = get(root, dotted);
  if (!node || !('$value' in node)) throw new Error(`unresolved token {${dotted}}`);
  return node.$value;
}

type Emitted = { path: string; vars: string[] };

function emitted(root: Node, prefix: string[] = []): Emitted[] {
  return Object.entries(root).flatMap(([key, child]) => {
    if (key.startsWith('$') || !child || typeof child !== 'object') return [];
    const node = child as Node;
    const here = [...prefix, key];
    if ('$value' in node) {
      const vars = (node.$extensions as Node | undefined)?.['relay.css'];
      return Array.isArray(vars) ? [{ path: here.join('.'), vars: vars as string[] }] : [];
    }
    return emitted(node, here);
  });
}

const FILES = ['colors.json', 'scale.json'] as const;

/** Resolved value of a token path, e.g. resolveToken('colors.json', 'semantic.ply.live'). */
export function resolveToken(file: (typeof FILES)[number], dotted: string): string {
  const root = read(file);
  return resolveValue(root, tokenValue(root, dotted));
}

export function buildTokensCss(): string {
  const lines: string[] = [];
  for (const file of FILES) {
    const root = read(file);
    for (const { path: dotted, vars } of emitted(root)) {
      const value = resolveValue(root, tokenValue(root, dotted));
      for (const name of vars) lines.push(`  --${name}: ${value};`);
    }
  }
  return [
    '/* Generated by `bun run tokens` from web/tokens/*.json. Do not edit by hand. */',
    '',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

if (import.meta.main) {
  writeFileSync(OUTPUT, buildTokensCss());
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)}`);
}
